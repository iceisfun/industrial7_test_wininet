#!/usr/bin/env bash
# Run corpus exes on the local Windows 10 22H2 VM and split the results per area. See docs/VM_RUN.md.
#
#   tools/vm_run.sh [options] AREA|EXE[,AREA|EXE...] ...
#   tools/vm_run.sh --all [options]
#
# options:
#   --all             every build/*.exe (dx_* only with --destructive)
#   --destructive     include dx_* areas
#   --filter SUBSTR   pass SUBSTR as the test-name filter (argv[1]) to every exe
#   --timeout SECS    per-exe timeout (default: max "VM_TIMEOUT: N" comment in tests/<area>/*.c, else 120)
#   --out DIR         results dir (default results/win10); one <area>.txt per exe + _vm_status.log
#   --runs DIR        where boot dirs (serial.log, payload) go (default ~/w10lab/runs)
#   --tag NAME        boot dir name prefix (default wininet)
#   --no-build        do not run make first
#   --extra FILE      copy FILE into the payload too (repeatable)
#
# What it does: stages the exes + build/tools/vmrun.exe + a generated run.cmd into a payload dir, boots
# ~/w10lab/tools/win10_run.sh (one guest at a time: that script holds ~/w10lab/oracle.lock and blocks),
# then tools/vm_split.py splits serial.log on the vmrun frames and validates every area (END marker, timeout,
# SUMMARY, byte count). Exes are packed into as few boots as fit a 900 s ORACLE_TIMEOUT cap (sum of per-exe
# timeouts + 150 s boot/drain). Exit code: 0 only if every area is PASS.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LAB="${W10LAB:-$HOME/w10lab}"
OUT="$ROOT/results/win10"; RUNS="$LAB/runs"; TAG=wininet; FILTER=""; TMO=""; ALL=0; DX=0; BUILD=1; EXTRA=(); ITEMS=()
while [ $# -gt 0 ]; do
  case "$1" in
    --all) ALL=1 ;;
    --destructive) DX=1 ;;
    --filter) FILTER="$2"; shift ;;
    --timeout) TMO="$2"; shift ;;
    --out) OUT="$2"; shift ;;
    --runs) RUNS="$2"; shift ;;
    --tag) TAG="$2"; shift ;;
    --no-build) BUILD=0 ;;
    --extra) EXTRA+=("$2"); shift ;;
    -h|--help) sed -n '2,25p' "$0"; exit 0 ;;
    *) IFS=',' read -ra parts <<< "$1"; ITEMS+=("${parts[@]}") ;;
  esac
  shift
done
cd "$ROOT"
if [ "$BUILD" = 1 ]; then make -s all >&2 || { echo "vm_run: build failed" >&2; exit 2; }; fi
[ -f build/tools/vmrun.exe ] || { echo "vm_run: build/tools/vmrun.exe missing (make)" >&2; exit 2; }
[ -x "$LAB/tools/win10_run.sh" ] || { echo "vm_run: $LAB/tools/win10_run.sh missing" >&2; exit 2; }
if [ ! -f "$LAB/LAB_READY" ] || [ ! -f "${W10_BASE:-$LAB/win10base.qcow2}" ]; then
  echo "vm_run: lab not ready ($LAB/LAB_READY or base image missing); waiting up to 40 min" >&2
  for i in $(seq 1 40); do sleep 60; [ -f "$LAB/LAB_READY" ] && [ -f "${W10_BASE:-$LAB/win10base.qcow2}" ] && break; done
  [ -f "$LAB/LAB_READY" ] || { echo "vm_run: lab still not ready" >&2; exit 2; }
fi

# resolve the exe list: names -> build/<name>.exe
EXES=()
if [ "$ALL" = 1 ]; then
  for e in build/*.exe; do n="$(basename "$e" .exe)"; [[ "$n" == dx_* && "$DX" = 0 ]] && continue; EXES+=("$e"); done
fi
for it in "${ITEMS[@]}"; do
  [ -z "$it" ] && continue
  if [ -f "$it" ]; then e="$it"; else e="build/$(basename "$it" .exe).exe"; fi
  [ -f "$e" ] || { echo "vm_run: no such exe: $it ($e)" >&2; exit 2; }
  n="$(basename "$e" .exe)"; [[ "$n" == dx_* && "$DX" = 0 ]] && { echo "vm_run: $n is destructive; pass --destructive" >&2; exit 2; }
  EXES+=("$e")
done
[ ${#EXES[@]} -gt 0 ] || { echo "vm_run: nothing to run (give AREA names or --all)" >&2; exit 2; }

tmo_for() {   # per-exe timeout
  local n="$1" t
  if [ -n "$TMO" ]; then echo "$TMO"; return; fi
  t="$(grep -ho 'VM_TIMEOUT: *[0-9]\+' "tests/$n"/*.c 2>/dev/null | grep -o '[0-9]\+' | sort -n | tail -1)"
  echo "${t:-120}"
}

# pack into boots
CAP=900; OVER=150
BOOTS=(); cur=""; cursum=0
for e in "${EXES[@]}"; do
  n="$(basename "$e" .exe)"; t="$(tmo_for "$n")"
  if [ -n "$cur" ] && [ $((cursum + t + OVER)) -gt $CAP ]; then BOOTS+=("$cur"); cur=""; cursum=0; fi
  cur="$cur $e"; cursum=$((cursum + t))
done
[ -n "$cur" ] && BOOTS+=("$cur")

mkdir -p "$OUT"; : > "$OUT/_vm_status.log"
STAMP="$(date +%Y%m%d-%H%M%S)"; rc=0; b=0
for boot in "${BOOTS[@]}"; do
  b=$((b + 1))
  BOOTDIR="$RUNS/$TAG-$STAMP-b$b"; PAY="$BOOTDIR/payload"; mkdir -p "$PAY"
  cp build/tools/vmrun.exe "$PAY/"
  for x in "${EXTRA[@]}"; do cp "$x" "$PAY/"; done
  sum=0; names=()
  {
    echo "@echo off"
    echo "rem generated by tools/vm_run.sh: only vmrun.exe writes COM1 while an exe runs (COM1 is exclusive, 04 F16)"
    echo "cd /d %~dp0"
    echo "echo @@I7 RUNSTART $TAG boot=$b %date% %time% > COM1"
    echo "ver > COM1"
    for e in $boot; do
      n="$(basename "$e" .exe)"; t="$(tmo_for "$n")"; sum=$((sum + t)); names+=("$n")
      cp "$e" "$PAY/"
      echo "vmrun.exe -t $t -n $n -- $n.exe${FILTER:+ \"$FILTER\"}"
    done
    echo "echo @@I7 RUNEND $TAG boot=$b %date% %time% > COM1"
  } > "$PAY/run.cmd"
  OT=$((sum + OVER)); [ $OT -gt $CAP ] && OT=$CAP
  echo "vm_run: boot $b/${#BOOTS[@]}: ${names[*]} (ORACLE_TIMEOUT=$OT) -> $BOOTDIR" >&2
  ORACLE_TIMEOUT=$OT "$LAB/tools/win10_run.sh" "$PAY" "$BOOTDIR" >&2
  if [ ! -s "$BOOTDIR/serial.log" ]; then echo "vm_run: empty serial.log for boot $b" >&2; fi
  grep -a -q "@@I7 RUNEND" "$BOOTDIR/serial.log" 2>/dev/null || echo "vm_run: boot $b did not reach RUNEND (guest died or ORACLE_TIMEOUT)" >&2
  exp="$(IFS=,; echo "${names[*]}")"
  python3 "$ROOT/tools/vm_split.py" "$BOOTDIR/serial.log" "$OUT" --expect "$exp" || rc=1
done
echo "vm_run: results in $OUT (status: $OUT/_vm_status.log)" >&2
exit $rc
