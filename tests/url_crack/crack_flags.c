TEST(url_crack_flags_decode_or_escape_both) {
    /* both bits together are accepted ((flags & 0x6fffffff) == 0); ESCAPE's in-situ decode then runs first */
    REQUIRE(U(InternetCrackUrlA));
    uc_crack_t o;
    uc_crackA("http://h/a%20b?c%20d", ICU_DECODE | ICU_ESCAPE, 1, &o);
    CHECKF(o.r, "err %lu", o.err);
    EXPECT_STR(o.path, "/a b");
    EXPECT_STR(o.extra, "?c d");
    t_note("DECODE|ESCAPE lengths: path %lu extra %lu", o.lpath, o.lextra);
}
TEST(url_crack_escape_file_url_stale_tail) {
    /* Win10 quirk: with ICU_ESCAPE the file: branch converts the decoded private copy with the ORIGINAL url length
     * (local_res10 in _InternetCrackUrlA is not updated by DecodeUrlInSitu), so the two characters freed by
     * decoding "%20" reappear at the end of the path: "C:\dir sp\file.txtxt", length 20. */
    REQUIRE(U(InternetCrackUrlA));
    uc_crack_t o;
    uc_crackA("file:///C:/dir%20sp/file.txt", ICU_ESCAPE, 1, &o);
    CHECK(o.r);
    EXPECT_STR(o.path, "C:\\dir sp\\file.txtxt");
    EXPECT_EQ(o.lpath, 20);
    uc_crackA("file:///C:/dir%20sp/file.txt", ICU_DECODE, 1, &o);
    CHECK(o.r);
    EXPECT_STR(o.path, "C:\\dir sp\\file.txt");
    EXPECT_EQ(o.lpath, 18);
}
