#!/usr/bin/env python3
"""Generate tests/http_body_io/bio_data.c: compressed response bodies for the decoding tests (bio_decode2.c).

Run from anywhere:  python3 tests/http_body_io/gen_bio_data.py
Needs the 'brotli' module for the br bodies. Every body is produced by zlib/gzip/brotli from known plain text,
so the expected decoded bytes are srv_fox_text(), srv_pattern_byte(i) or zeros (see bio_data.h).
"""
import os, struct, zlib, brotli

FOX = b"The quick brown fox jumps over the lazy dog.\n" * 20
assert len(FOX) == 900


def pattern(n):
    return bytes((ord('a') + (i * 7 + i // 26) % 26) for i in range(n))


def raw_deflate(data, level=9):
    c = zlib.compressobj(level, zlib.DEFLATED, -15)
    return c.compress(data) + c.flush()


def gz(data, flg=0, fname=b"", fextra=b"", fcomment=b"", crc_xor=0, isize_add=0, mtime=0):
    hdr = bytearray(b"\x1f\x8b\x08") + bytes([flg]) + struct.pack("<I", mtime) + b"\x00\x03"
    if flg & 4:
        hdr += struct.pack("<H", len(fextra)) + fextra
    if flg & 8:
        hdr += fname + b"\x00"
    if flg & 16:
        hdr += fcomment + b"\x00"
    if flg & 2:
        hdr += struct.pack("<H", zlib.crc32(bytes(hdr)) & 0xFFFF)
    crc = (zlib.crc32(data) ^ crc_xor) & 0xFFFFFFFF
    return bytes(hdr) + raw_deflate(data) + struct.pack("<II", crc, (len(data) + isize_add) & 0xFFFFFFFF)


def zl(data, adler_xor=0):
    body = zlib.compress(data, 9)
    a = struct.unpack(">I", body[-4:])[0] ^ adler_xor
    return body[:-4] + struct.pack(">I", a)


BODIES = [
    # name, bytes, comment
    ("br_fox", brotli.compress(FOX, quality=11), "brotli(fox text)"),
    ("br_pat100k", brotli.compress(pattern(100000), quality=5), "brotli(pattern 100000)"),
    ("br_empty", brotli.compress(b""), "brotli of 0 bytes"),
    ("gz_fname", gz(FOX, 8, fname=b"fox.txt"), "gzip FNAME"),
    ("gz_fextra", gz(FOX, 4, fextra=b"AB\x02\x00xy"), "gzip FEXTRA (one 2-byte subfield)"),
    ("gz_fcomment", gz(FOX, 16, fcomment=b"a comment"), "gzip FCOMMENT"),
    ("gz_fhcrc", gz(FOX, 2), "gzip FHCRC"),
    ("gz_allflags", gz(FOX, 2 | 4 | 8 | 16, fname=b"n", fextra=b"XY\x00\x00", fcomment=b"c"), "gzip FHCRC|FEXTRA|FNAME|FCOMMENT"),
    ("gz_ftext_mtime", gz(FOX, 1, mtime=0x5F000000), "gzip FTEXT + MTIME"),
    ("gz_badcrc", gz(FOX, crc_xor=0x01010101), "gzip with a wrong CRC32 trailer"),
    ("gz_badisize", gz(FOX, isize_add=7), "gzip with a wrong ISIZE trailer"),
    ("gz_two_members", gz(b"first-member|") + gz(b"second-member"), "two gzip members back to back"),
    ("gz_trailing_garbage", gz(FOX) + b"GARBAGE-AFTER-MEMBER", "gzip member followed by junk"),
    ("gz_empty", gz(b""), "gzip of 0 bytes"),
    ("gz_zeros1m", gz(bytes(1048576)), "gzip of 1 MiB of zero bytes"),
    ("gz_pat300k", gz(pattern(300000)), "gzip(pattern 300000), real Huffman"),
    ("zl_badadler", zl(FOX, adler_xor=0x00010001), "zlib with a wrong Adler-32 trailer"),
    ("zl_pat100k", zl(pattern(100000)), "zlib(pattern 100000)"),
    ("raw_pat100k", raw_deflate(pattern(100000)), "raw deflate(pattern 100000)"),
    ("gz_no_trailer", gz(FOX)[:-8], "gzip without the 8-byte trailer"),
]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = [
        "/* bio_data.c - GENERATED by gen_bio_data.py, do not edit. Compressed bodies for bio_decode2.c. Not a test file. */",
        '#include "bio_data.h"',
    ]
    hdr = [
        "/* bio_data.h - GENERATED by gen_bio_data.py. Plain texts: fox = srv_fox_text() (900 bytes),",
        " * pattern N = srv_pattern_byte(0..N-1), zeros = N zero bytes. */",
        "#ifndef BIO_DATA_H", "#define BIO_DATA_H", "#include <stddef.h>",
    ]
    for name, data, comment in BODIES:
        out.append(f"/* {comment}: {len(data)} bytes */")
        out.append(f"const unsigned char bio_{name}[] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        if not data:
            out.append("    0")
        out.append("};")
        out.append(f"const size_t bio_{name}_len = {len(data)};")
        hdr.append(f"extern const unsigned char bio_{name}[]; extern const size_t bio_{name}_len;  /* {comment} */")
    hdr.append("#endif")
    with open(os.path.join(here, "bio_data.c"), "w") as f:
        f.write("\n".join(out) + "\n")
    with open(os.path.join(here, "bio_data.h"), "w") as f:
        f.write("\n".join(hdr) + "\n")


if __name__ == "__main__":
    main()
