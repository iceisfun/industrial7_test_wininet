#!/usr/bin/env python3
"""Regenerate gs_exptab.c from tools/<module>_exports.json (Win10 19041 reference export tables).
usage: python3 tests/gopher_and_stubs/gen_exptab.py > tests/gopher_and_stubs/gs_exptab.c"""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
MODS = ["wininet", "urlmon", "winhttp", "sspicli", "schannel", "crypt32", "ws2_32"]
out = ["/* GENERATED by gen_exptab.py from tools/<module>_exports.json (corpus: Win10 19041 export tables). Do not edit. */",
       '#include "gs.h"', ""]
for m in MODS:
    d = json.load(open(os.path.join(ROOT, "tools", f"{m}_exports.json")))
    d.sort(key=lambda e: e["ordinal"])
    out.append(f"const gs_export gs_exp_{m}[] = {{")
    for e in d:
        n = '"%s"' % e["name"] if e["name"] else "NULL"
        f = '"%s"' % e["forwarder"] if e["forwarder"] else "NULL"
        out.append(f"    {{ {n}, {e['ordinal']}, 0x{(e['rva'] or 0):x}, {f} }},")
    out.append("};")
    out.append(f"const size_t gs_exp_{m}_n = sizeof gs_exp_{m} / sizeof gs_exp_{m}[0];")
    out.append("")
print("\n".join(out))
