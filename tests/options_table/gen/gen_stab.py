#!/usr/bin/env python3
"""Freeze the InternetSetOption matrix observed on the Win10 VM into ot_stab.c.

usage: gen_stab.py <probe output (S lines)> > ../ot_stab.c
Probe: gen/probe.c (CHILD setp, one process per option). Token order per option:
  for h in S,C,R,X,N: for w in A,W: nul0,nul4,buf0,len1,len3,rt ; then for w in A,W: len8z,len5,d0,d1,dbig
Token: "ok" (TRUE), "-" (rt not attempted because the query failed), "<err>" (FALSE + GetLastError),
       "skip" (not run in a non-destructive area, see SKIP below)."""
import re, sys, collections
V1 = ['nul0', 'nul4', 'buf0', 'len1', 'len3', 'rt']
V2 = ['len8z', 'len5', 'd0', 'd1', 'dbig']
# 42 END_BROWSER_SESSION and 154 (0x9a) call EndBrowserSession: never run outside dx_*.
# 75 PER_CONNECTION_OPTION: the round-trip set reaches SetPerConnOptions (per-user registry) -> skip rt only.
SKIP_ALL = {42, 154}
SKIP_RT = {75}
rows = collections.defaultdict(dict)
for l in open(sys.argv[1]):
    m = re.match(r'S (\d+) (\w) (\w) (\w+) r=(\d) e=(\d+)', l)
    if not m: continue
    o, h, w, v, r, e = m.groups()
    rows[int(o)][(h, w, v)] = 'ok' if r == '1' else e
print('/* GENERATED by gen/gen_stab.py from the Win10 22H2 VM probe (gen/probe.c, CHILD setp). Do not edit by hand. */')
print('#include "ot_tab.h"')
print('const ot_stab_row ot_stab[] = {')
for o in sorted(rows):
    toks = []
    for h in 'SCRXN':
        for w in 'AW':
            for v in V1:
                t = rows[o].get((h, w, v), '-')
                if o in SKIP_ALL or (o in SKIP_RT and v == 'rt'): t = 'skip'
                toks.append(t)
        for w in 'AW':
            for v in V2:
                t = rows[o].get((h, w, v), '-')
                if o in SKIP_ALL: t = 'skip'
                toks.append(t)
    print('    { %d, "%s" },' % (o, ','.join(toks)))
print('};')
print('const int ot_stab_n = sizeof ot_stab / sizeof ot_stab[0];')
