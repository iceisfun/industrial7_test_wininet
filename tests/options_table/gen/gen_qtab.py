#!/usr/bin/env python3
"""Freeze the InternetQueryOptionA/W matrix observed on the Win10 VM into ot_qtab.c.

usage: gen_qtab.py <probe output with Q lines (plain or .gz)> > ../ot_qtab.c
Probe: gen/probe.c (tests pq_NNN), handle kinds N S C R X T F L (ot.h), probes q0..q3 (ot_tab.h).
Volatility rules (environment-dependent values are not frozen, see EVIDENCE.md):
  VOL_ALL  : the whole row is only noted (timing / socket / thread state)
  VOL_LEN  : q1..q3 length depends on port, path, user, time: only r/e are checked
  VOL_DATA : value not frozen (pointers, handles, paths, certificates, times)
Data is frozen only for successful q1 results of at most 16 bytes that are not VOL_DATA."""
import re, sys, gzip

def opn(p):
    return gzip.open(p, 'rt') if p.endswith('.gz') else open(p)

# (option, kinds or '*') -> flags
VOL_LEN, VOL_DATA, VOL_ALL = 1, 2, 4
RULES = {
    1: ('*', VOL_DATA),            # CALLBACK pointer
    21: ('*', VOL_DATA),           # PARENT_HANDLE: handle values depend on allocation order
    24: ('*', VOL_DATA),           # EXTENDED_ERROR: last socket error of the thread
    27: ('*', VOL_DATA),           # CACHE_STREAM_HANDLE
    32: ('*', VOL_DATA | VOL_LEN), # SECURITY_CERTIFICATE_STRUCT: pointers + dates
    33: ('*', VOL_DATA | VOL_LEN), # DATAFILE_NAME: cache path (user profile)
    34: ('XTRL', VOL_DATA | VOL_LEN),  # URL: ephemeral port / scratch path
    35: ('*', VOL_DATA | VOL_LEN), # SECURITY_CERTIFICATE (formatted, dates)
    40: ('*', 0),
    66: ('*', VOL_DATA),           # security connection info (cert pointer, cipher)
    67: ('*', VOL_DATA),           # DIAGNOSTIC_SOCKET_INFO: socket handle / ports
    69: ('*', VOL_DATA),           # CACHE_TIMESTAMPS
    105: ('*', VOL_DATA),          # SERVER_CERT_CHAIN_CONTEXT pointer
    109: ('*', VOL_DATA | VOL_LEN),
    117: ('*', VOL_DATA | VOL_LEN),
    129: ('*', VOL_DATA | VOL_LEN),
}
EXTRA_VOL = {}   # filled from a second probe run when available: (opt, kind, w) -> flags

rows = {}
order = []
for l in opn(sys.argv[1]):
    m = re.match(r'Q (-?\d+) (\w) (\w) (\d) r=(\d) e=(\d+) l=(\d+)(?: d=([0-9a-f]*))?', l)
    if not m: continue
    opt, k, w, p, r, e, ln, d = m.groups()
    key = (int(opt), k, w)
    if key not in rows: rows[key] = {}; order.append(key)
    rows[key][int(p)] = (int(r), int(e), int(ln), d)

def cstr(s): return 'NULL' if s is None else '"%s"' % s
print('/* GENERATED by gen/gen_qtab.py from the Win10 22H2 VM probe (gen/probe.c). Do not edit by hand. */')
print('#include "ot_tab.h"')
print('const ot_qrow ot_qtab[] = {')
for key in order:
    opt, k, w = key
    pr = rows[key]
    flags = 0
    if opt in RULES and (RULES[opt][0] == '*' or k in RULES[opt][0]): flags |= RULES[opt][1]
    flags |= EXTRA_VOL.get(key, 0)
    def t(i):
        if i not in pr: return (-1, 0, 0)
        return pr[i][:3]
    r0, r1, r2, r3 = t(0), t(1), t(2), t(3)
    data = None
    if r1[0] == 1 and not (flags & (VOL_DATA | VOL_ALL)):
        nbytes = r1[2] * (2 if w == 'W' else 1) if opt in (28, 29, 34, 41, 43, 44, 53, 83, 33) else r1[2]
        d = pr[1][3] or ''
        if nbytes <= 16 and len(d) >= 2 * nbytes: data = d[:2 * nbytes]
    print('    { %d, \'%s\', %d, %d,%du,%du, %d,%du,%du, %d,%du,%du, %d,%du,%du, %du, %s },' % (
        opt, k, 1 if w == 'W' else 0, r0[0], r0[1], r0[2], r1[0], r1[1], r1[2], r2[0], r2[1], r2[2], r3[0], r3[1], r3[2], flags, cstr(data)))
print('};')
print('const int ot_qtab_n = sizeof ot_qtab / sizeof ot_qtab[0];')
