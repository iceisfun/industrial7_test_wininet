#!/usr/bin/env python3
"""Freeze the set -> query round-trip matrix observed on the Win10 VM into ot_rtab.c.

usage: gen_rtab.py <probe output with RTQ/RTS/RTPASS lines (plain or .gz)> [more outputs ...] > ../ot_rtab.c
Probe: gen/probe.c (TEST zz_probe_rt -> CHILD rtp <opt>, run twice per boot). Per option and handle kind N S C R
(N = NULL handle, S session, C unsent HTTP connect to 127.0.0.1:1, R unsent request on C):
  q(-1)  then for v in 0,1,2,3,4,0x10,0x7fffffff,0x80000000: set A (len 4) -> s(v), query A -> q(v)
Tokens (one per step, comma separated, 4 x 17 per option):
  set:   "ok" | "<err>"
  query: "<len>=<hex of the first min(len,8) bytes>" on success | "!<err>/<len>" on failure
  "*"    differs between the probe passes/boots (or in VOLATILE below): not compared
  "-"    not run
Every input file and both passes in each must agree for a token to be frozen."""
import re, sys, gzip, collections

VALS = [0, 1, 2, 3, 4, 0x10, 0x7fffffff, 0x80000000]
KINDS = 'NSCR'
# query data that is a pointer / handle / time / socket error: keep r/e/len, mask the bytes
VOLATILE_DATA = {1, 21, 24, 27, 32, 33, 35, 66, 67, 69, 105, 109, 117, 129, 186, 192}

def opn(p):
    return gzip.open(p, 'rt', errors='replace') if p.endswith('.gz') else open(p, errors='replace')

runs = []   # list of dict opt -> list of tokens
for path in sys.argv[1:]:
    cur = None; pass_no = None; per_pass = collections.defaultdict(dict)
    for line in opn(path):
        m = re.match(r'RTPASS (\d+) (\d+)', line)
        if m:
            pass_no = int(m.group(1)); continue
        m = re.match(r'RTQ (\d+) (\w) (-?\d+) qr=(\d) qe=(\d+) ql=(\d+) qd=([0-9a-f]*)', line)
        if m and pass_no is not None:
            o, k, v, r, e, l, d = m.groups(); o = int(o)
            if o in VOLATILE_DATA and r == '1': d = 'x'
            tok = ('%s=%s' % (l, d)) if r == '1' else ('!%s/%s' % (e, l))
            per_pass[(pass_no, o)][(k, int(v), 'q')] = tok
            continue
        m = re.match(r'RTS (\d+) (\w) (\d+) sr=(\d) se=(\d+)', line)
        if m and pass_no is not None:
            o, k, v, r, e = m.groups()
            per_pass[(pass_no, int(o))][(k, int(v), 's')] = 'ok' if r == '1' else e
    for (p, o), d in per_pass.items():
        toks = []
        for k in KINDS:
            toks.append(d.get((k, -1, 'q'), '-'))
            for v in VALS:
                toks.append(d.get((k, v, 's'), '-'))
                toks.append(d.get((k, v, 'q'), '-'))
        runs.append((o, toks))

merged = {}
for o, toks in runs:
    if o not in merged: merged[o] = list(toks); continue
    m = merged[o]
    for i, t in enumerate(toks):
        if m[i] != t: m[i] = '*'

print('/* GENERATED by gen/gen_rtab.py from the Win10 22H2 VM probe (gen/probe.c, CHILD rtp). Do not edit by hand. */')
print('#include "ot_tab.h"')
print('const ot_stab_row ot_rtab[] = {')
for o in sorted(merged):
    print('    { %d, "%s" },' % (o, ','.join(merged[o])))
print('};')
print('const int ot_rtab_n = sizeof ot_rtab / sizeof ot_rtab[0];')
